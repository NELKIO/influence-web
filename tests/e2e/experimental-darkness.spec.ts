import { expect, test } from '@playwright/test';
import { expectNoErrors, fresh, waitGame } from './helpers';

test('experimental darkness is opt-in, persists and hides the ordinary map preview', async ({ page }) => {
  const errors = await fresh(page);
  await page.getByRole('button', { name: 'Новая битва' }).click();
  const map = page.locator('.steps button').nth(0);
  const modes = page.locator('.steps button').nth(2);
  await modes.click();
  const dark = page.getByRole('switch', { name: 'Тьма', exact: true });
  const fire = page.getByRole('switch', { name: 'Сигнальные огни' });
  const blind = page.getByRole('switch', { name: 'Абсолютная тьма' });
  await expect(page.getByText('Экспериментальные режимы', { exact: true })).toBeVisible();
  await expect(fire).not.toBeChecked();
  await expect(blind).not.toBeChecked();
  await dark.click();
  await map.click();
  await expect(page.locator('.map-preview [data-unknown-map]')).toHaveCount(0);
  const original = await page.locator('.map-preview svg').first().innerHTML();
  await modes.click();
  await blind.click();
  await blind.click();
  await map.click();
  await expect.poll(() => page.locator('.map-preview svg').first().innerHTML()).not.toBe(original);
  await modes.click();
  await fire.click();
  await blind.click();
  await dark.click();
  await expect(fire).not.toBeChecked();
  await expect(blind).not.toBeChecked();
  await blind.click();
  await expect(dark).toBeChecked();
  await map.click();
  await expect(page.locator('.map-preview [data-unknown-map]')).toBeVisible();
  await expect(page.locator('.map-preview')).not.toContainText(/\d+ клет/);
  await page.reload();
  await expect(page.locator('.map-preview [data-unknown-map]')).toBeVisible();
  await modes.click();
  await expect(blind).toBeChecked();
  await expect(fire).not.toBeChecked();
  await page.getByRole('button', { name: /^В бой/ }).first().click();
  await waitGame(page);
  const { known, total } = await page.evaluate(() => {
    const { ctrl } = (window as any).__infweb;
    return { known: ctrl.view().known?.reduce((a: number, b: number) => a + b, 0), total: ctrl.state.field.cells.length };
  });
  expect(known).toBeGreaterThan(0);
  expect(known).toBeLessThan(total);
  await expect(page.getByTestId('signal-fire')).toHaveCount(0);
  await expectNoErrors(errors);
});

test('a real signal fire can be cancelled, lit once, survives reload and expires on the next own turn', async ({ page }, testInfo) => {
  const errors = await fresh(page, { confirmEnd: false });
  await page.evaluate(() => localStorage.setItem('infweb.setup', JSON.stringify({ size: 'M', players: ['human', 'human'], darkness: true, blind: true, signalFires: true, shuffle: false, rev: 2 })));
  await page.reload();
  await page.getByRole('button', { name: /Быстрый старт/ }).click();
  await waitGame(page);
  const handover = page.getByTestId('handover');
  const fire = page.getByTestId('signal-fire');
  const signal = () => page.evaluate(() => (window as any).__infweb.ctrl.state.signalFireCells?.[0] ?? -1);
  const live = () => page.evaluate(() => (window as any).__infweb.ctrl.view().visible.reduce((a: number, b: number) => a + b, 0));
  await expect(handover).toBeVisible();
  expect(await live()).toBe(0);
  await handover.click();
  const before = await live();
  await fire.click();
  await expect(fire).toHaveAttribute('aria-pressed', 'true');
  await fire.click();
  expect(await signal()).toBe(-1);
  await fire.click();
  const [x, y] = await page.evaluate(() => {
    const { ctrl, renderer } = (window as any).__infweb;
    const mine = ctrl.state.field.cells.findIndex((c: { owner: number }) => c.owner === 0);
    const [x, y] = renderer.cellScreenPos(mine);
    const rect = renderer.canvas.getBoundingClientRect();
    return [x + rect.left, y + rect.top];
  });
  if (testInfo.project.use.hasTouch) await page.touchscreen.tap(x, y);
  else await page.mouse.click(x, y);
  await expect(fire).toBeDisabled();
  expect(await signal()).toBeGreaterThanOrEqual(0);
  expect(await live()).toBeGreaterThan(before);
  await page.reload();
  await page.locator('.play-btn.cont').click();
  await waitGame(page);
  await handover.click();
  await expect(fire).toBeDisabled();
  const pass = async () => {
    await page.locator('.end-btn').click();
    await page.locator('.end-btn').click();
  };
  await pass();
  await expect(handover).toBeVisible();
  expect(await live()).toBe(0);
  await handover.click();
  expect(await signal()).toBeGreaterThanOrEqual(0);
  await pass();
  await handover.click();
  expect(await signal()).toBe(-1);
  expect(await live()).toBe(before);
  await expect(fire).toBeEnabled();
  await expectNoErrors(errors);
});

test('giving the first seat to GOD keeps the last person’s view covered until handover', async ({ page }) => {
  const errors = await fresh(page, { speed: 'slow' });
  await page.evaluate(() => localStorage.setItem('infweb.setup', JSON.stringify({ size: 'M', players: ['human', 'human', 'dummy'], darkness: true, blind: true, shuffle: false, rev: 2 })));
  await page.reload();
  await page.getByRole('button', { name: /Быстрый старт/ }).click();
  await waitGame(page);
  const handover = page.getByTestId('handover');
  await handover.click();
  await page.getByRole('button', { name: 'Пауза' }).click();
  const surrender = page.getByRole('button', { name: 'Сдаться', exact: true });
  await surrender.click();
  await page.getByRole('radio', { name: 'Передать новому БОГУ' }).check();
  await surrender.click();
  await expect(handover).toBeVisible();
  expect(await page.evaluate(() => (window as any).__infweb.ctrl.overlay.next)).toBe(1);
  expect(await page.evaluate(() => (window as any).__infweb.ctrl.view().known.some(Boolean))).toBe(false);
  await handover.click();
  expect(await page.evaluate(() => (window as any).__infweb.ctrl.view().known.some(Boolean))).toBe(true);
  await expectNoErrors(errors);
});
